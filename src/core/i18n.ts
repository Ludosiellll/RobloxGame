export type TextKey = keyof typeof RU
const DICT: Record<Lang, typeof RU> = { ru: RU, en: EN }

export function tr(lang: Lang, key: TextKey, vars: Record<string, string | number> = {}): string {
  const raw = DICT[lang][key] ?? RU[key] ?? key
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`))
}

/** 5.4 → «5,4» по-русски, «5.4» по-английски. */
export function fmt(lang: Lang, value: number, digits = 2): string {
  const s = value.toFixed(digits).replace(/\.?0+$/, '')
  return lang === 'ru' ? s.replace('.', ',') : s
}
